from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any


def generate_report(
    analysis: dict[str, Any],
    cleaning_summary: dict[str, Any] | None = None,
    *,
    filename: str = "uploaded_dataset.csv",
    generated_at: datetime | None = None,
) -> str:
    """
    Generate a plain-text report from analysis and optional cleaning results.

    `analysis` is the dictionary returned by csv_cleaner.analyze().
    `cleaning_summary` is the summary returned by csv_cleaner.clean_dataframe().
    """
    required_keys = {"total_rows", "total_columns", "duplicate_rows",
                     "total_missing_cells", "columns"}
    missing_keys = required_keys.difference(analysis)
    if missing_keys:
        raise ValueError(
            f"Analysis report is missing required fields: {sorted(missing_keys)}"
        )

    timestamp = generated_at or datetime.now()
    lines: list[str] = [
        "=" * 72,
        "                    CSV DATA QUALITY REPORT",
        "=" * 72,
        f"Generated : {timestamp.strftime('%Y-%m-%d %H:%M:%S')}",
        f"File      : {Path(filename).name}",
        "",
        "DATASET OVERVIEW",
        "-" * 72,
        f"Total rows          : {analysis['total_rows']:,}",
        f"Total columns       : {analysis['total_columns']:,}",
        f"Duplicate rows      : {analysis['duplicate_rows']:,}",
        f"Missing cells       : {analysis['total_missing_cells']:,}",
        "",
        "COLUMN-LEVEL ANALYSIS",
        "-" * 72,
    ]

    if analysis["columns"]:
        for column, details in analysis["columns"].items():
            lines.extend([
                f"\n{column}",
                f"  Data type          : {details['dtype']}",
                f"  Missing values     : {details['missing']:,}",
                f"  Missing percentage : {details['missing_pct']:.1f}%",
                f"  Unique values      : {details['unique_values']:,}",
                f"  Quality status     : {details['status']}",
            ])
    else:
        lines.append("No columns found.")

    if cleaning_summary is not None:
        lines.extend([
            "",
            "CLEANING SUMMARY",
            "-" * 72,
            f"Rows before cleaning       : {cleaning_summary['original_rows']:,}",
            f"Rows after cleaning        : {cleaning_summary['cleaned_rows']:,}",
            f"Duplicate rows found       : {cleaning_summary['duplicates_found']:,}",
            f"Duplicate rows removed     : {cleaning_summary['duplicates_removed']:,}",
            f"Missing cells before      : {cleaning_summary['missing_cells_before']:,}",
            f"Numeric values filled      : {cleaning_summary['numeric_missing_filled']:,}",
            f"Text values filled         : {cleaning_summary['text_missing_filled']:,}",
            f"Missing cells remaining    : {cleaning_summary['missing_cells_remaining']:,}",
            f"Whitespace cells trimmed   : {cleaning_summary['whitespace_cells_trimmed']:,}",
            "",
            "CLEANING CONFIGURATION",
            "-" * 72,
            f"Numeric missing strategy : {cleaning_summary['numeric_strategy']}",
            f"Text missing strategy    : {cleaning_summary['text_strategy']}",
            f"Remove duplicates        : {cleaning_summary['duplicate_removal_enabled']}",
            f"Trim whitespace          : {cleaning_summary['whitespace_trimming_enabled']}",
        ])

        empty_numeric = cleaning_summary.get("columns_without_numeric_values", [])
        if empty_numeric:
            lines.extend([
                "",
                "NOTE: These numeric columns had no valid values to calculate "
                "a replacement:",
                *[f"  - {column}" for column in empty_numeric],
            ])

    lines.extend([
        "",
        "=" * 72,
        "Generated by CSV Cleaner & Report Generator",
        "Silver Bullet | https://github.com/silverbullet-ai",
        "=" * 72,
        "",
    ])
    return "\n".join(lines)


def save_report(
    report_text: str,
    original_filename: str | Path,
    output_path: str | Path | None = None,
) -> str:
    """Save report text, defaulting to a sibling *_report.txt file."""
    original = Path(original_filename)
    destination = (
        Path(output_path)
        if output_path is not None
        else original.with_name(f"{original.stem}_report.txt")
    )

    if destination.resolve() == original.resolve():
        raise ValueError("Report path must not overwrite the original input file.")

    destination.write_text(report_text, encoding="utf-8")
    return str(destination)
